package com.enterprise.fraud.repository;

import com.enterprise.fraud.entity.FraudAlert;
import com.enterprise.fraud.entity.FraudAlert.AlertStatus;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Query;
import org.springframework.stereotype.Repository;

import java.util.List;

/**
 * Spring Data JPA repository for FraudAlert entities.
 * Provides query methods for alert management and dashboard analytics.
 */
@Repository
public interface FraudAlertRepository extends JpaRepository<FraudAlert, Long> {

    /**
     * Find alerts by status.
     */
    List<FraudAlert> findByStatus(AlertStatus status);

    /**
     * Find alerts by status with pagination.
     */
    Page<FraudAlert> findByStatus(AlertStatus status, Pageable pageable);

    /**
     * Find alerts for a specific transaction.
     */
    List<FraudAlert> findByTransactionId(Long transactionId);

    /**
     * Find alerts with risk score above a threshold.
     */
    List<FraudAlert> findByRiskScoreGreaterThanEqual(Double threshold);

    /**
     * Count alerts by status.
     */
    long countByStatus(AlertStatus status);

    /**
     * Count alerts predicted as fraud.
     */
    long countByPredictionTrue();

    /**
     * Find alerts generated by a specific model.
     */
    List<FraudAlert> findByModelUsed(String modelUsed);

    /**
     * Get the average risk score across all alerts.
     */
    @Query("SELECT AVG(fa.riskScore) FROM FraudAlert fa")
    Double findAverageRiskScore();

    /**
     * Find the most recent alerts ordered by timestamp.
     */
    List<FraudAlert> findTop10ByOrderByAlertTimestampDesc();
}
